function ErrorComponent({ error }: ErrorComponentProps) {
  if (process.env["NODE_ENV"] !== "production") {
    console.error("Root boundary caught error:", error);
  }

  return (
    <div className="min-h-screen bg-[#0A0A0A] text-[#FBF9F5] flex items-center justify-center p-6">
      <div className="max-w-md w-full border border-[#262626] p-6 rounded-lg bg-[#111111]">
        <h1 className="font-mono text-lg font-bold text-[#E5484D] mb-2">System Error</h1>
        <p className="text-sm text-neutral-400 mb-4">
          An unexpected error occurred while rendering the queue interface.
        </p>
        <button
          onClick={() => window.location.reload()}
          className="w-full bg-[#FBF9F5] text-[#0A0A0A] py-2 text-sm font-medium rounded hover:bg-white transition"
        >
          Reload Page
        </button>
      </div>
    </div>
  );
}

